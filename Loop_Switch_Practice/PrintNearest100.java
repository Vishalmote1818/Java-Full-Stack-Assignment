public class PrintNearest100 {
    
    public static void main(String[] args) {
        int n1=70;
        int n2=34;

        if(n1>n2 && n1<=100){
            System.out.println(n1+" is nearest to 100");
        }
        else{

            System.out.println(n2+" is nearest to 100");
        }
    }
}
