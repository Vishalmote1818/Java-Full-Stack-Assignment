public class CheckMultiple{

    public static void main(String[] args) {
        
        int n=55;

        if(n%5==0 && n%11==0){

            System.out.println(n+" is multiple of 5 and 11");
        }
        else{

            System.out.println(n+" is not multiple of 5 and 11");

        }
    }
}